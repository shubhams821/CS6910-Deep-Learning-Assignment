    def rmsprop(self, x_train, y_train, x_val, y_val):
        eta = self.l_rate
        beta = 0.9  # RMSprop decay factor
        epsilon = 1e-8
        v_w, v_b = self.initialize_gradients()  # Initialize moving average of squared gradients
        for epoch in range(self.epochs):
            for x, y in tqdm(zip(x_train, y_train), total=len(x_train)):
                activations, pre_activations = self.forward_propagation(x)
                current_gradients_w, current_gradients_b, _, _ = self.backward_propagation(y, activations, pre_activations)
                for i in range(1, self.L):
                    v_w[i-1] = beta * v_w[i-1] + (1 - beta) * np.square(current_gradients_w[i-1])
                    v_b[i-1] = beta * v_b[i-1] + (1 - beta) * np.square(current_gradients_b[i-1])
                    self.parameters_w[i] -= (eta / np.sqrt(v_w[i-1] + epsilon)) * current_gradients_w[i-1]
                    self.parameters_b[i] -= (eta / np.sqrt(v_b[i-1] + epsilon)) * current_gradients_b[i-1]
            train_acc, train_loss, _, _ = self.model_performance(x_train, y_train)
            val_acc, val_loss, _, _ = self.model_performance(x_val, y_val)
            print("Training Accuracy = ",train_acc)
