    # Activation function for the hidden layers
    def activation(self, x, derivative=False):
        if self.activation_func == 'sigmoid':
            if derivative:
                return (np.exp(-x))/((np.exp(-x)+1)**2)
            return 1/(1 + np.exp(-x))
        elif self.activation_func == 'tanh':
            temp1 = (np.exp(x) - np.exp(-x))/(np.exp(x) + np.exp(-x))
            if derivative:
                return 1 - (temp1)**2
            return temp1
        elif self.activation_func == 'relu':
            if derivative:
                return 1. * (x > 0)
            return x * (x > 0)

    # Activation function for the output layer
    def output_activation(self, x, derivative=False):
        if self.output_activ_func == 'softmax':
            exps = np.exp(x - x.max())
            if derivative:
                return exps / np.sum(exps, axis=0) * (1 - exps / np.sum(exps, axis=0))
            return exps / np.sum(exps, axis=0)

    # Initializing the parameters -- weights and biases
    def initialize_model_parameters(self):
        parameters_w = [0]
        parameters_b = [0]
        for l in range(1, self.L):
            if self.initializer == 'random':
                parameters_w.append(np.random.randn(self.layer_sizes[l], self.layer_sizes[l - 1])*0.1)
            elif self.initializer == 'xavier':
                parameters_w.append(np.random.randn(self.layer_sizes[l], self.layer_sizes[l - 1]) * np.sqrt(2/ (self.layer_sizes[l - 1] + self.layer_sizes[l])))
            parameters_b.append(np.zeros((self.layer_sizes[l], 1)))
        return parameters_w, parameters_b

    # Initialize gradients
    def initialize_gradients(self):
        gradients_w = []
        gradients_b = []
        for l in range(1, self.L):
            gradients_w.append(np.zeros((self.layer_sizes[l], self.layer_sizes[l - 1])))
            gradients_b.append(np.zeros((self.layer_sizes[l], 1)))
        return gradients_w, gradients_b

    # Forward Propagation
    def forward_propagation(self, x):
        pre_activations = [0]
        activations = []

        activations.append(x.reshape(len(x), 1))

        # From layer 1 to L-1
        for i in range(1, self.L-1):
            pre_activations.append(self.parameters_b[i] + np.matmul(self.parameters_w[i], activations[i-1]))
            activations.append(self.activation(pre_activations[i], derivative=False))

        # Last layer L
        pre_activations.append(self.parameters_b[self.L-1] + np.matmul(self.parameters_w[self.L-1], activations[self.L-2]))
        activations.append(self.output_activation(pre_activations[self.L-1]))

        return activations, pre_activations

    # Back Propagation
    def backward_propagation(self, y, activations, pre_activations):
        gradients_w, gradients_b = self.initialize_gradients()
        gradients_a = [None] * self.L
        gradients_h = [None] * self.L

        # Compute output gradient
        f_x = activations[self.L-1]
        e_y = y.reshape(len(y), 1)

        # Gradient with respect to last layer
        if self.loss_func == 'cross_entropy':
            gradients_a[self.L-1] = (f_x - e_y)
        elif self.loss_func == 'squared_error':
            gradients_a[self.L-1] = (f_x - e_y)*f_x*(1-f_x)

        # Compute gradients for hidden layers
        for k in range(self.L-1, 0, -1):
            gradients_w[k-1] = np.outer(gradients_a[k], activations[k-1])
            gradients_b[k-1] = gradients_a[k]
            gradients_h[k-1] = np.dot(self.parameters_w[k].T, gradients_a[k])
            if k > 1:
                gradients_a[k-1] = gradients_h[k-1] * self.activation(pre_activations[k-1], derivative=True)

        return gradients_w, gradients_b, gradients_a, gradients_h

    # Compute Loss
    def compute_loss(self, yHat, y):
        if self.loss_func == 'cross_entropy':
            indexClass = np.argmax(y)
            prob = yHat[indexClass]
            if(prob<=0):
                prob = prob + 0.0000000001
            loss = -np.log(prob)
            return loss
        if self.loss_func == 'squared_error':
            loss = 0.5*np.sum((y-yHat)**2)
            return loss

    # Find the accuracy
    def model_performance(self, x_test, y_test):
        predictions = []
        y_true = []
        y_pred = []
        loss = []
        for x, y in zip(x_test ,y_test):
            activations, pre_activations = self.forward_propagation(x)
            predicted_class = np.argmax(activations[self.L-1])
            y = y.reshape(len(y), 1)
            actual_class = np.argmax(y)
            y_true.append(actual_class)
            y_pred.append(predicted_class)
            predictions.append(predicted_class == actual_class)
            loss.append(self.compute_loss(activations[self.L-1], y))

        accuracy = (np.sum(predictions)*100)/len(predictions)
        tot_loss = np.sum(loss)/len(loss)

        return accuracy, tot_loss, y_true, y_pred

    # Optimization Algorithm: Stochastic Gradient Descent
    def stochastic_gradient_descent(self, x_train, y_train, x_val, y_val):
        eta = self.l_rate

        for epoch in range(self.epochs):
            print(" =============== Epoch Number: " + str(epoch+1) + " =============== ")

            # Initialize the gradients
            gradients_w, gradients_b = self.initialize_gradients()

            # Learn the parameters
            for x, y in tqdm(zip(x_train, y_train), total=len(x_train)):

                # Forward Propagation
                activations, pre_activations = self.forward_propagation(x)

                # Backward Propagation
                current_gradients_w, current_gradients_b, _, _ = self.backward_propagation(y, activations, pre_activations)

                # Update parameters
                for i in range(1,self.L):
                    self.parameters_w[i] = self.parameters_w[i] - eta * current_gradients_w[i-1]
                    self.parameters_b[i] = self.parameters_b[i] - eta * current_gradients_b[i-1]

            # Validation Accuracy
            train_acc, train_loss, _, _ = self.model_performance(x_train, y_train)
            val_acc, val_loss, _, _ = self.model_performance(x_val, y_val)
            print("Training Accuracy = ",train_acc)
            print("Training Loss = ",train_loss)
            print("Validation Accuracy = ",val_acc)
            print("Validation Loss = ",val_loss)
            wandb.log({"val_acc": val_acc, "train_acc": train_acc, "val_loss": val_loss, "train_loss": train_loss, "epoch": epoch+1})


    def momentum_gradient_descent(self, x_train, y_train, x_val, y_val):
        eta = self.l_rate
        beta = 0.9  # Momentum hyperparameter
        v_w, v_b = self.initialize_gradients()  # Initialize velocity
        for epoch in range(self.epochs):
            for x, y in tqdm(zip(x_train, y_train), total=len(x_train)):
                activations, pre_activations = self.forward_propagation(x)
                current_gradients_w, current_gradients_b, _, _ = self.backward_propagation(y, activations, pre_activations)
                for i in range(1, self.L):
                    v_w[i-1] = beta * v_w[i-1] + (1 - beta) * current_gradients_w[i-1]
                    v_b[i-1] = beta * v_b[i-1] + (1 - beta) * current_gradients_b[i-1]
                    self.parameters_w[i] -= eta * v_w[i-1]
                    self.parameters_b[i] -= eta * v_b[i-1]
            train_acc, train_loss, _, _ = self.model_performance(x_train, y_train)
            val_acc, val_loss, _, _ = self.model_performance(x_val, y_val)
            print("Training Accuracy = ",train_acc)
